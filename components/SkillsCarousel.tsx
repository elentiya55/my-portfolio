const BOUNCE_DELAYS = ICONS.map((_, i) => (i * 2.8) / ICONS.length);
const SPEED = 0.6;

export default function SkillsCarousel() {
  const { theme } = useTheme();
  const iconSet = [...ICONS, ...ICONS];
  const trackRef = useRef<HTMLDivElement>(null);
  const posRef = useRef(0);
  const rafRef = useRef<number>(0);
  const pausedRef = useRef(false);

  useEffect(() => {
    const track = trackRef.current;
    if (!track) return;

    const animate = () => {
      if (!pausedRef.current) {
        const setWidth = track.scrollWidth / 2;
        posRef.current -= SPEED;
        if (posRef.current <= -setWidth) posRef.current += setWidth;
        track.style.transform = `translateX(${posRef.current}px)`;
      }
      rafRef.current = requestAnimationFrame(animate);
    };

    rafRef.current = requestAnimationFrame(animate);
    return () => cancelAnimationFrame(rafRef.current);
  }, []);

  return (
    <section
      className="carousel-section"
      onMouseEnter={() => { pausedRef.current = true; }}
      onMouseLeave={() => { pausedRef.current = false; }}
    >
      <div className="carousel-container" style={{ position: 'relative' }}>
        <div className="carousel-track" ref={trackRef}>
          {iconSet.map((icon, idx) => (
            <div
              key={`${icon.id}-${idx}`}
              className="carousel-icon"
              style={{ animationDelay: `${BOUNCE_DELAYS[idx % ICONS.length]}s` }}
            >
              <svg viewBox="0 0 50 50" width="50" height="50" aria-label={icon.label}>
                {icon.paths.map((p, i) =>
                  p.type === 'polygon' ? (
                    <polygon key={i} points={p.points} />
                  ) : (
                    <path key={i} d={p.d} />
                  )
                )}
              </svg>
              <span className="carousel-label">{icon.label}</span>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}
